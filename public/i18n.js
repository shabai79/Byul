function detectLang() {
  try { const saved = localStorage.getItem('byul.lang'); if (saved && LANGS[saved]) return saved; } catch {}
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (LANGS[code]) return code;
  }
  return 'en';
}
let lang = detectLang();
function setLang(code) {
  if (!LANGS[code]) return;
  lang = code;
  try { localStorage.setItem('byul.lang', code); } catch {}
}
function t(key, vars = {}) {
  const s = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? MESSAGES.ko[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}
const locale = () => LOCALES[lang];
// HTML 안의 data-i18n / data-i18n-ph 속성을 현재 언어로 채움
function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  document.documentElement.lang = lang;
  document.title = 'Byul · ' + t('app.title');
}
